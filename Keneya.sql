-- SGBD : PostgreSQL (Supabase)
--
-- IMPORTANT :
-- Les identifiants metier sont des BIGINT auto-incrementes.
-- Supabase Auth utilise obligatoirement UUID pour auth.users.id.
-- La colonne profils.auth_user_id conserve donc ce type pour
-- relier le profil au compte d'authentification.
-- =========================================================

-- 1. PROFILS
CREATE TABLE IF NOT EXISTS public.profils (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID NOT NULL UNIQUE
        REFERENCES auth.users(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('militaire', 'medecin', 'specialiste')),
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    matricule VARCHAR(50) NOT NULL UNIQUE,
    grade VARCHAR(100),
    region VARCHAR(100),
    email VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. UNITES
CREATE TABLE IF NOT EXISTS public.unites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    region VARCHAR(100) NOT NULL
);

-- 3. SPECIALITES
CREATE TABLE IF NOT EXISTS public.specialites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE
        CHECK (code IN (
            'cardiologie',
            'dermatologie',
            'ophtalmologie',
            'traumatologie',
            'psychiatrie',
            'generale',
            'autre'
        )),
    libelle VARCHAR(100) NOT NULL
);

-- 4. MILITAIRES
CREATE TABLE IF NOT EXISTS public.militaires (
    profil_id BIGINT PRIMARY KEY
        REFERENCES public.profils(id) ON DELETE CASCADE,
    unite_id BIGINT
        REFERENCES public.unites(id) ON DELETE SET NULL,
    groupe_sanguin VARCHAR(5),
    date_naissance DATE
);

-- 5. MEDECINS
CREATE TABLE IF NOT EXISTS public.medecins (
    profil_id BIGINT PRIMARY KEY
        REFERENCES public.profils(id) ON DELETE CASCADE,
    service VARCHAR(100)
);

-- 6. SPECIALISTES
CREATE TABLE IF NOT EXISTS public.specialistes (
    profil_id BIGINT PRIMARY KEY
        REFERENCES public.profils(id) ON DELETE CASCADE,
    specialite_id BIGINT NOT NULL
        REFERENCES public.specialites(id)
);

-- 7. DEMANDES
CREATE TABLE IF NOT EXISTS public.demandes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(30) NOT NULL UNIQUE,
    militaire_id BIGINT NOT NULL
        REFERENCES public.militaires(profil_id),
    medecin_id BIGINT NOT NULL
        REFERENCES public.medecins(profil_id),
    specialite_id BIGINT NOT NULL
        REFERENCES public.specialites(id),
    niveau_gene VARCHAR(20) NOT NULL
        CHECK (niveau_gene IN ('faible', 'modere', 'important')),
    depuis_quand VARCHAR(30) NOT NULL
        CHECK (depuis_quand IN (
            'aujourd_hui',
            'quelques_jours',
            '1_2_semaines',
            '1_mois',
            'plus'
        )),
    symptomes VARCHAR(1000) NOT NULL,
    infos_complementaires VARCHAR(300),
    statut VARCHAR(20) NOT NULL DEFAULT 'en_attente'
        CHECK (statut IN ('en_attente', 'en_cours', 'traitee')),
    reponse TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    traitee_at TIMESTAMPTZ
);

-- 8. REFERENCES_SPECIALISTES
CREATE TABLE IF NOT EXISTS public.references_specialistes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(30) NOT NULL UNIQUE,
    demande_id BIGINT NOT NULL
        REFERENCES public.demandes(id) ON DELETE CASCADE,
    medecin_id BIGINT NOT NULL
        REFERENCES public.medecins(profil_id),
    specialiste_id BIGINT NOT NULL
        REFERENCES public.specialistes(profil_id),
    specialite_id BIGINT NOT NULL
        REFERENCES public.specialites(id),
    statut VARCHAR(20) NOT NULL DEFAULT 'en_attente'
        CHECK (statut IN ('en_attente', 'en_cours', 'traitee')),
    avis TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    avis_at TIMESTAMPTZ
);

-- INDEX POUR LES RECHERCHES ET LES JOINTURES
CREATE INDEX IF NOT EXISTS idx_militaires_unite
    ON public.militaires(unite_id);

CREATE INDEX IF NOT EXISTS idx_demandes_militaire
    ON public.demandes(militaire_id);

CREATE INDEX IF NOT EXISTS idx_demandes_medecin
    ON public.demandes(medecin_id);

CREATE INDEX IF NOT EXISTS idx_demandes_statut
    ON public.demandes(statut);

CREATE INDEX IF NOT EXISTS idx_references_demande
    ON public.references_specialistes(demande_id);

CREATE INDEX IF NOT EXISTS idx_references_specialiste
    ON public.references_specialistes(specialiste_id);

